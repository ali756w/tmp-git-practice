def add(a, b):
    """
    this function adds two numbers
    """
    return a + b

def sub(a, b):
    """
    this function subtracts two numbers
    """
    return a - b

def mul(a, b):
    """
    this function multiplies two numbers
    """
    return a * b

def div(a, b):
    """
    this function divides two numbers
    """
    return a / b

def pow(a, b):
    """
    this function raises a number to the power of another
    """
    return a ** b